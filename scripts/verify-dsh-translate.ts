const readJsonl = (path: string): unknown[] => {
  let raw: string
  try { raw = readFileSync(path, 'utf8') } catch { return [] }
  return raw.split('\n').filter(line => line.trim() !== '').map(line => JSON.parse(line) as unknown)
}

